"""`rrs ledger render`: ledger/claims-ledger.md for reading (spec 02 section 10)."""

from __future__ import annotations

from rrs.config import Repo
from rrs.jsonio import fmt_time
from rrs.ledger.models import load_claims, load_recruiters, load_rules, load_targets
from rrs.ledger.tally import compute, fmt_range


def _cell(s: str | None) -> str:
    return " ".join((s or "").split()).replace("|", "\\|")


def locator(anchor) -> str:
    ts = fmt_time(anchor.t_start)
    return f"{anchor.sentence_id}" + (f" [{ts}]" if ts else "") + f' q:"{_cell(anchor.quote)}"'


def render_ledger(repo: Repo) -> str:
    claims = load_claims(repo)
    rules = load_rules(repo)
    recruiters = load_recruiters(repo)
    targets = load_targets(repo)
    tally = compute(repo, claims, rules)
    t = tally["totals"]
    out = [
        "# Claims ledger",
        "",
        "Generated by `rrs ledger render` from `ledger/claims.jsonl`, `rules.yaml`, `recruiters.yaml`"
        " and `targets.yaml`. Do not edit.",
        "",
        "## Conventions",
        "",
        "- Type: `F` fact or practice, `F!` fact reporting rejection on it, `P` preference or advice.",
        "- Stance: `+` supports the rule, `-` contradicts it, `~` qualifies it (listed, not counted).",
        "- Labels: Consensus (3+ distinct recruiters), Supported (2), Single source (1), Contested "
        "(supporters and opposers both exist). Counting rules: ADR 0001.",
        "- Locator: sentence ID, `[HH:MM:SS]` when the source has timing, then the exact quote.",
        "- Only guest claims count"
        + ("; independent host claims count too." if tally["count_independent_hosts"] else
           "; host claims marked independent are listed but not counted."),
        "",
        f"Totals: {t['sources']} sources, {t['recruiters']} recruiters, {t['claims']} claims, "
        f"{t['rules']} rules, {t['out_of_scope_rules']} out of scope.",
        "",
        "## Recruiter profiles",
        "",
    ]
    match = targets.default_target.match if targets else {}
    if targets:
        out += [f"Default target `{targets.default}`: {targets.default_target.description}.", ""]
    out += ["| Code | Name | Type | Title | Region | Industry | Roles hired | Year | Sources | "
            "Match | Caveats |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for code, r in recruiters.items():
        year = f"{r.year} ({r.year_basis})" if r.year else r.year_basis
        out.append(f"| {code} | {r.name} | {r.type} | {_cell(r.title)} | {_cell(r.region)} | "
                   f"{_cell(r.industry)} | {_cell(r.roles_hired)} | {year} | {', '.join(r.sources)} | "
                   f"{match.get(code, '')} | {_cell(r.caveats)} |")
    out += ["", "## Rule index", ""]
    if not rules:
        out += ["No rules yet.", ""]
    else:
        out += ["| ID | Rule and check | Evidence | Base severity | For | Against | Notes |",
                "|---|---|---|---|---|---|---|"]
        for rid in tally["order"]:
            r = tally["rules"][rid]
            text = f"{_cell(r['text'])} *Check:* {_cell(r['check'])}"
            if r["status"] != "active":
                text = f"(retired) {text}"
            c = r["claims"]
            out.append(f"| {rid} | {text} | {r['evidence']} | {r['severity']} | "
                       f"{', '.join(c['for'])} | {', '.join(c['against'])} | {', '.join(c['notes'])} |")
        out.append("")
    by_recruiter: dict[str, list] = {}
    for c in claims:
        by_recruiter.setdefault(c.recruiter, []).append(c)
    for code in sorted(by_recruiter, key=lambda k: list(recruiters).index(k) if k in recruiters else 99):
        name = recruiters[code].name if code in recruiters else code
        out += [f"## {code} {name} ({len(by_recruiter[code])} claims)", "",
                "| ID | Locator | Episode | Type | Stance | Rules | Claim | Notes |",
                "|---|---|---|---|---|---|---|---|"]
        for c in by_recruiter[code]:
            loc = "<br>".join(locator(a) for a in c.anchors)
            if c.quote_en:
                loc += f"<br>*{_cell(c.quote_en)}*"
            claim = c.claim_en
            if c.value is not None:
                rule = next((r for r in rules if r.id in c.rules and r.measure), None)
                unit = rule.measure.unit if rule else ""
                claim += f" *Value:* {fmt_range(c.value.min, c.value.max, unit)}" + (
                    f" ({c.value.condition})" if c.value.condition else "")
            notes = [c.notes] if c.notes else []
            if c.speaker_role == "host":
                notes.insert(0, "host, independent")
            if c.attribution == "content-override":
                notes.insert(0, "content-override")
            out.append(f"| {c.id} | {loc} | {c.episode or ''} | {c.type} | {c.stance} | "
                       f"{', '.join(c.rules)} | {_cell(claim)} | {_cell('; '.join(notes))} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def run_render(repo: Repo) -> str:
    text = render_ledger(repo)
    path = repo.ledger / "claims-ledger.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return text
