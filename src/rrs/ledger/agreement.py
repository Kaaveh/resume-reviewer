"""`rrs ledger agree`: compare two independent extractions of one source at the rule level
(spec 02 section 12). Explanations of the differences are written by hand in a notes YAML
(`ledger/agreement/<source>.yaml`, rule ID -> text) and rendered into the report, because
`reports/*` is generated."""

from __future__ import annotations

from pathlib import Path

from rrs.jsonio import read_jsonl, read_yaml
from rrs.ledger.models import rule_sort_key


def load_rows(paths: list[Path], recruiter: str | None) -> list[dict]:
    rows = [r for p in paths for r in read_jsonl(p)]
    return [r for r in rows if recruiter is None or r["recruiter"] == recruiter]


def profile(rows: list[dict]) -> dict[str, dict]:
    """Per rule: stances used, and whether a counted (+ or -) claim is F/F! and F!."""
    out: dict[str, dict] = {}
    for r in rows:
        for rid in r["rules"]:
            p = out.setdefault(rid, {"stances": set(), "fact": False, "reject": False, "claims": 0})
            p["stances"].add(r["stance"])
            p["claims"] += 1
            if r["stance"] in "+-":
                p["fact"] |= r["type"] in ("F", "F!")
                p["reject"] |= r["type"] == "F!"
    return out


def counted(p: dict) -> set[str]:
    return p["stances"] & {"+", "-"}


def type_class(p: dict) -> str:
    return "F!" if p["reject"] else "F" if p["fact"] else "P"


def compare(a_rows: list[dict], b_rows: list[dict]) -> dict:
    a, b = profile(a_rows), profile(b_rows)
    ra = {rid for rid, p in a.items() if counted(p)}
    rb = {rid for rid, p in b.items() if counted(p)}
    both = ra & rb
    stance_same = {rid for rid in both if counted(a[rid]) == counted(b[rid])}
    type_same = {rid for rid in both if type_class(a[rid]) == type_class(b[rid])}
    return {
        "a": a, "b": b, "a_rules": ra, "b_rules": rb, "matched": both,
        "a_found_by_b": len(both) / len(ra) if ra else 1.0,
        "b_found_by_a": len(both) / len(rb) if rb else 1.0,
        "stance_agreement": len(stance_same) / len(both) if both else 1.0,
        "type_agreement": len(type_same) / len(both) if both else 1.0,
        "stance_differs": sorted(both - stance_same, key=rule_sort_key),
        "type_differs": sorted(both - type_same, key=rule_sort_key),
        "only_a": sorted(ra - rb, key=rule_sort_key),
        "only_b": sorted(rb - ra, key=rule_sort_key),
        "a_claims": len(a_rows), "b_claims": len(b_rows),
    }


def render(result: dict, source: str, a_name: str, b_name: str, notes: dict[str, str],
           target: float = 0.8) -> str:
    a, b = result["a"], result["b"]

    def desc(p: dict | None) -> str:
        if p is None:
            return "not used"
        return f"{''.join(sorted(p['stances']))} {type_class(p)} ({p['claims']} claims)"

    ok = result["a_found_by_b"] >= target and result["b_found_by_a"] >= target
    out = [
        f"# Agreement study: {source}",
        "",
        "Generated by `rrs ledger agree`; explanations come from the notes file. Do not edit.",
        "",
        f"- A: {a_name} ({result['a_claims']} claims, {len(result['a_rules'])} rules with + or -)",
        f"- B: {b_name} ({result['b_claims']} claims, {len(result['b_rules'])} rules with + or -)",
        "",
        "| Measure | Value |",
        "|---|---|",
        f"| Rules of A found by B | {result['a_found_by_b']:.2f} |",
        f"| Rules of B found by A | {result['b_found_by_a']:.2f} |",
        f"| Stance agreement on matched rules | {result['stance_agreement']:.2f} |",
        f"| Type agreement on matched rules (F!, F, P) | {result['type_agreement']:.2f} |",
        "",
        f"Target: at least {target} of each extraction's rules found by the other: "
        + ("met." if ok else "not met."),
        "",
        "## Differences",
        "",
    ]
    rows = [(rid, "only in A") for rid in result["only_a"]]
    rows += [(rid, "only in B") for rid in result["only_b"]]
    rows += [(rid, "stance differs") for rid in result["stance_differs"]]
    rows += [(rid, "type differs") for rid in result["type_differs"] if rid not in
             result["stance_differs"]]
    rows.sort(key=lambda x: rule_sort_key(x[0]))
    if not rows:
        out += ["None.", ""]
    else:
        out += ["| Rule | Difference | A | B | Explanation |", "|---|---|---|---|---|"]
        for rid, kind in rows:
            note = " ".join((notes.get(rid) or "*not explained yet*").split())
            out.append(f"| {rid} | {kind} | {desc(a.get(rid))} | {desc(b.get(rid))} | {note} |")
        out.append("")
    out += ["## Matched rules", ""]
    out.append(", ".join(sorted(result["matched"], key=rule_sort_key)) or "None.")
    if notes.get("_summary"):
        out += ["", "## Summary", "", notes["_summary"].strip()]
    return "\n".join(out).rstrip() + "\n"


def run_agree(a: list[Path], b: list[Path], source: str, recruiter: str | None,
              notes_path: Path | None) -> tuple[dict, str]:
    notes = (read_yaml(notes_path) or {}) if notes_path and notes_path.exists() else {}
    result = compare(load_rows(a, recruiter), load_rows(b, recruiter))
    names = (", ".join(p.name for p in a), ", ".join(p.name for p in b))
    return result, render(result, source, *names, notes)
