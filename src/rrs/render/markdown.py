"""Render corpus/Sxxx/transcript.md from transcript.json and episodes.yaml."""

from __future__ import annotations

import html
import re

from rrs.config import Repo
from rrs.glossary import load_people
from rrs.jsonio import fmt_time, read_json
from rrs.segment.episodes import load_episodes
from rrs.sources import Source, load_source

_MD_SPECIAL = re.compile(r"([\\`*_<>\[\]])")


def _md_escape(text: str) -> str:
    return _MD_SPECIAL.sub(r"\\\1", text)


def _sentence_block(turn: dict, s: dict, timing: bool) -> str:
    ts = fmt_time(s["start"]) if timing else None
    head = f"**{turn['person']}**{' [' + ts + ']' if ts else ''} `{s['id']}`"
    host = turn["role"] == "host"
    if s["lang"] in ("fa", "mixed"):
        body = html.escape(s["text"], quote=False)
        body = f"<em>{body}</em>" if host else body
        return f'{head}\n<div dir="rtl">{body}</div>'
    body = _md_escape(s["text"])
    return f"{head}\n{'*' + body + '*' if host else body}"


def render(transcript: dict, source: Source, names: dict[str, str], episodes: dict) -> str:
    timing = transcript["timing"] != "none"
    people = ", ".join(
        f"{p.person} {names.get(p.person, p.person)} ({p.role})" for p in source.people
    )
    duration = fmt_time(source.duration_s) if source.duration_s is not None else "unknown"
    out = [
        f"# {transcript['source_id']} · {source.title}",
        "",
        "Generated by `rrs render`; do not edit.",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| URL | {source.url or 'unknown'} |",
        f"| Upload date | {source.upload_date or 'unknown'} |",
        f"| Duration | {duration} |",
        f"| People | {people} |",
        f"| Transcript file | `{source.transcript_file}` |",
        f"| Transcript version | {transcript['transcript_version']} |",
        f"| Timing | {transcript['timing']} |",
        "",
    ]
    current = object()
    for turn in transcript["turns"]:
        for s in turn["sentences"]:
            if s["episode"] != current:
                current = s["episode"]
                ep = episodes.get(current)
                label = f" · {ep.label}" if ep else ""
                ts = fmt_time(s["start"]) if timing else None
                out += [f"## {current or 'No episode'}{label}{' [' + ts + ']' if ts else ''}", ""]
            out += [_sentence_block(turn, s, timing), ""]
    return "\n".join(out).rstrip() + "\n"


def run_render(repo: Repo, source_id: str) -> str:
    source = load_source(repo, source_id)
    transcript = read_json(repo.transcript_path(source_id))
    names = {k: v.name for k, v in load_people(repo).people.items()}
    episodes = (
        {e.id: e for e in load_episodes(repo, source_id)}
        if repo.episodes_path(source_id).exists()
        else {}
    )
    text = render(transcript, source, names, episodes)
    repo.render_path(source_id).write_text(text, encoding="utf-8")
    return text
